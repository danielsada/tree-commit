"""Generate filetypes_data.go from a release of pre-commit's identify library.

Usage: python tools/gen_filetypes.py (or `go generate`). Needs network access.
"""

import urllib.request

VERSION = "v2.6.20"
BASE = f"https://raw.githubusercontent.com/pre-commit/identify/{VERSION}"


def fetch(path: str) -> str:
    with urllib.request.urlopen(f"{BASE}/{path}") as resp:
        return resp.read().decode()


def load(path: str) -> dict:
    namespace: dict = {}
    exec(fetch(path), namespace)  # noqa: S102 - plain data modules from a pinned release
    return namespace


def go_map(name: str, doc: str, data: dict) -> str:
    lines = [f"// {doc}", f"var {name} = map[string][]string{{"]
    for key in sorted(data):
        tags = ", ".join(f'"{t}"' for t in sorted(data[key]))
        lines.append(f'\t"{key}": {{{tags}}},')
    lines.append("}")
    return "\n".join(lines)


def main() -> None:
    ext = load("identify/extensions.py")
    interp = load("identify/interpreters.py")
    license_text = fetch("LICENSE").strip()
    parts = [
        f"// Code generated by tools/gen_filetypes.py from pre-commit/identify {VERSION}. DO NOT EDIT.",
        "//",
        *(f"// {line}".rstrip() for line in license_text.splitlines()),
        "",
        "package main",
        "",
        "//go:generate python tools/gen_filetypes.py",
        "",
        go_map("extensionTags", "extensionTags maps lower-case file extensions to type tags.", ext["EXTENSIONS"]),
        "",
        go_map(
            "extensionTagsNeedBinaryCheck",
            "extensionTagsNeedBinaryCheck maps extensions whose files can be text or binary.",
            ext["EXTENSIONS_NEED_BINARY_CHECK"],
        ),
        "",
        go_map("nameTags", "nameTags maps well-known file names to type tags.", ext["NAMES"]),
        "",
        go_map("interpreterTags", "interpreterTags maps shebang interpreters to type tags.", interp["INTERPRETERS"]),
        "",
    ]
    with open("filetypes_data.go", "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(parts))


if __name__ == "__main__":
    main()